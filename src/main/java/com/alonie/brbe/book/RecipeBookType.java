package com.alonie.brbe.book;

/** The three container types supported by BRBE recipe books. */
public enum RecipeBookType {
    /** Vanilla crafting table + 2×2 survival inventory. */
    CRAFTING,
    /** Brewing stand with potion/splash/lingering categories. */
    BREWING,
    /** Smithing table with transform/trim categories. */
    SMITHING
}
